/// ПАМЯТЬ О ПРОВЕРКАХ УЗЛОВ.
///
/// Зачем это вообще. Раньше «пинг» был TCP-коннектом до адреса узла. В России этого мало:
/// при глушении интернета адрес прямого узла остаётся достижимым (порт принимает соединение),
/// а туннель через него не работает — сессию рвёт фильтрация. У пользователя это выглядело
/// издевательски: у всех серверов зелёный отклик, подключаешься — и ничего не грузится, при
/// этом узлы через CDN работают нормально. Приложение показывало доступным то, чем пользоваться
/// нельзя, и «лучший сервер» выбирал именно такой узел.
///
/// Сама проверка живёт в движке ([TunnelEngine.probe]): он поднимает временный экземпляр на один
/// узел и тянет сквозь него маленький ответ из сети. Здесь — что мы с её итогом ДЕЛАЕМ: помним,
/// показываем и на основании этого выбираем сервер.

/// Приговор по узлу на КОНКРЕТНОЙ сети.
///
/// Привязка к сети обязательна: узел, заблокированный у мобильного оператора, прекрасно работает
/// с домашнего Wi-Fi. Без неё приложение переносило бы приговор с одной сети на другую и врало бы
/// ровно так же, как раньше врал TCP-пинг.
class NodeVerdict {
  /// Прошёл ли трафик сквозь узел.
  final bool ok;

  /// Время ответа СКВОЗЬ туннель, мс (null, если не прошёл).
  final int? ms;
  final DateTime at;

  /// Отпечаток сети, на которой получен приговор.
  final String net;

  const NodeVerdict({required this.ok, required this.at, required this.net, this.ms});

  bool get fresh => DateTime.now().difference(at) < kVerdictTtl;

  Map<String, dynamic> toJson() => {'ok': ok, 'ms': ms, 'at': at.toIso8601String(), 'net': net};

  static NodeVerdict? fromJson(Object? j) {
    if (j is! Map) return null;
    final at = DateTime.tryParse('${j['at']}');
    if (at == null) return null;
    return NodeVerdict(
      ok: j['ok'] == true,
      ms: (j['ms'] is num) ? (j['ms'] as num).toInt() : null,
      at: at,
      net: '${j['net'] ?? ''}',
    );
  }
}

/// Сколько приговор считается свежим. Блокировки меняются в течение суток, а переспрашивать
/// каждую минуту дорого: полчаса — компромисс между «не врать» и «не гонять движок впустую».
const Duration kVerdictTtl = Duration(minutes: 30);

/// Как узел выглядит для пользователя.
enum NodeState {
  /// проверен на этой сети и пропускает трафик
  works,

  /// проверен и НЕ пропускает — выбирать нечего
  blocked,

  /// не проверялся здесь или приговор устарел
  unknown,
}
